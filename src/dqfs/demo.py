"""Demo data generator: a SQLite database with realistic quality problems.

``dqfs demo`` creates ``demo/quality_demo.db`` with two tables:

* ``customers`` (~2.6k rows) carrying controlled corruption: missing cells,
  duplicate business keys, malformed emails, outliers, mixed phone formats
  and stale purchase timestamps - enough for every factor to tell a story;
* ``orders`` with orphaned customer references.

It also writes ``demo/dqfs-demo.yaml`` wired to the generated database so
``dqfs score`` runs out of the box.
"""

from __future__ import annotations

import logging
from datetime import datetime, timedelta
from pathlib import Path

import numpy as np
import pandas as pd
from sqlalchemy import create_engine

logger = logging.getLogger(__name__)

_N_ROWS = 2500
_N_DUPLICATES = 75
_N_ORDERS = 5000
_SEED = 2026

_COUNTRIES = ["US", "GB", "DE", "FR", "IN", "CN"]
_COUNTRY_P = [0.30, 0.15, 0.20, 0.10, 0.15, 0.10]


def _iso(dt: datetime) -> str:
    return dt.strftime("%Y-%m-%d %H:%M:%S")


def build_customers(now: datetime) -> pd.DataFrame:
    """Build the deliberately imperfect customers table."""
    rng = np.random.default_rng(_SEED)
    n = _N_ROWS
    ids = np.arange(1, n + 1, dtype=np.int64)

    ages = rng.integers(18, 76, n).astype(float)
    ages[rng.random(n) < 0.02] = np.nan                       # 2% missing
    outlier_idx = rng.choice(n, size=int(n * 0.01), replace=False)
    ages[outlier_idx[: len(outlier_idx) // 2]] = 250.0        # impossible age
    ages[outlier_idx[len(outlier_idx) // 2:]] = -5.0

    income = np.round(np.exp(rng.normal(10.8, 0.35, n)), 2)   # ~ 49k median
    income[rng.random(n) < 0.03] = np.nan                     # 3% missing
    income[rng.random(n) < 0.005] *= 50                       # extreme outliers

    country = pd.Series(
        rng.choice(_COUNTRIES, n, p=_COUNTRY_P), dtype=object
    )
    country[rng.random(n) < 0.08] = None                      # 8% missing
    country[rng.random(n) < 0.01] = "XX"                      # invalid code

    email = np.array([f"user{i}@example.com" for i in ids], dtype=object)
    email[rng.random(n) < 0.02] = "user(at)example"           # malformed
    email[rng.random(n) < 0.03] = None                        # 3% missing

    phone_main = np.array([f"{1000 + int(i) % 9000:04d}" for i in ids])
    phone = np.where(
        rng.random(n) < 0.70,
        np.array([f"555-{p}" for p in phone_main], dtype=object),
        np.array([f"555 {p}" for p in phone_main], dtype=object),   # mixed format
    )

    signup_days = rng.integers(30, 730, n)
    signup = np.array(
        [_iso(now - timedelta(days=int(d))) for d in signup_days], dtype=object
    )
    purchase_days = rng.gamma(2.0, 25.0, n).clip(1, 400)      # median ~ 42d
    purchase = np.array(
        [_iso(now - timedelta(days=float(d))) for d in purchase_days], dtype=object
    )

    churn_prob = (
        0.10 + 0.25 * (ages > 60) + 0.20 * (income < 35_000)
    ).clip(0.0, 0.9)
    churn = (rng.random(n) < churn_prob).astype(int)

    df = pd.DataFrame({
        "id": ids,
        "email": email,
        "age": ages,
        "income": income,
        "country": country,
        "phone": phone,
        "signup_date": signup,
        "last_purchase_at": purchase,
        "churn": churn,
    })
    duplicates = df.sample(_N_DUPLICATES, random_state=_SEED)
    return pd.concat([df, duplicates], ignore_index=True)


def build_orders(n_customers: int) -> pd.DataFrame:
    """Build the orders table including orphaned customer references."""
    rng = np.random.default_rng(_SEED + 1)
    customer_id = rng.integers(1, n_customers + 1, _N_ORDERS)
    orphan_mask = rng.random(_N_ORDERS) < 0.02                   # 2% orphans
    orphans = rng.integers(900000, 990000, size=int(orphan_mask.sum()))
    customer_id[orphan_mask] = orphans
    return pd.DataFrame({
        "order_id": np.arange(1, _N_ORDERS + 1),
        "customer_id": customer_id,
        "amount": np.round(np.exp(rng.normal(4.0, 0.8, _N_ORDERS)), 2),
        "order_date": [
            _iso(datetime(2026, 1, 1) - timedelta(days=int(d)))
            for d in rng.integers(1, 365, _N_ORDERS)
        ],
    })


_DEMO_CONFIG = """\
# Generated by `dqfs demo` - wired to demo/quality_demo.db
dataset:
  name: customers_demo
  owner: data-platform-team

factors:
  timeliness:
    column: last_purchase_at
    fresh_days: 30
    stale_days: 90
  uniqueness:
    key_columns: [id]
  consistency:
    checks:
      - {left: age, op: '>=', right: '18'}
    format_columns: [phone, email]
  validity:
    constraints:
      age: {min: 0, max: 120}
      income: {min: 0}
      email: {regex: '^[^@\\s]+@[^@\\s]+\\.[A-Za-z]{2,}$'}
"""


def generate_demo(out_dir: str | Path = "demo") -> tuple[Path, Path]:
    """Generate the demo database and its config.

    Returns:
        ``(db_path, config_path)``.
    """
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    db_path = out / "quality_demo.db"
    if db_path.exists():
        db_path.unlink()
    now = datetime.now().astimezone()
    customers = build_customers(now)
    orders = build_orders(_N_ROWS)
    engine = create_engine(f"sqlite:///{db_path}")
    try:
        customers.to_sql("customers", engine, index=False, if_exists="replace")
        orders.to_sql("orders", engine, index=False, if_exists="replace")
    finally:
        engine.dispose()
    config_path = out / "dqfs-demo.yaml"
    config_path.write_text(_DEMO_CONFIG, encoding="utf-8")
    logger.info(
        "demo database written: %s (customers=%d, orders=%d)",
        db_path, len(customers), len(orders),
    )
    return db_path, config_path
