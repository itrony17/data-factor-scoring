"""DQFS command-line interface.

Subcommands
-----------
``demo``     generate a SQLite demo database with realistic quality issues
``score``    run the full scoring pipeline and write all report artifacts
``report``   re-render HTML/Excel/CSV artifacts from ``results/latest.json``
``publish``  commit the result artifacts to a GitHub repository
``doctor``   self-check the environment, config and data source
``init``     write a starter ``dqfs.yaml``

Exit codes: 0 success, 1 unexpected error, 2 config, 3 data load,
4 scoring, 5 report, 6 publish, 7 quality-gate failure (with
``--fail-on-gate``).
"""

from __future__ import annotations

import argparse
import json
import logging
import shutil
import sys
from collections.abc import Callable
from pathlib import Path

from dqfs import __version__
from dqfs.config import load_config
from dqfs.demo import generate_demo
from dqfs.errors import (
    ConfigError,
    DataLoadError,
    DqfsError,
    GateFailureError,
    PublishError,
    ReportError,
    ScoringError,
)
from dqfs.io_loader import load_table
from dqfs.logging_setup import setup_logging
from dqfs.scoring import run_scoring

logger = logging.getLogger(__name__)

_EXIT_CODES: tuple[tuple[type[Exception], int], ...] = (
    (GateFailureError, 7),
    (PublishError, 6),
    (ReportError, 5),
    (ScoringError, 4),
    (DataLoadError, 3),
    (ConfigError, 2),
)

_STARTER_CONFIG = """\
# DQFS starter configuration - generated by `dqfs init`
# Full option reference: see dqfs.yaml in the repository README.
dataset:
  name: my_dataset
thresholds:
  factor_pass: 0.85
  factor_warn: 0.65
  composite_pass: 80.0
  composite_warn: 65.0
factors:
  timeliness:
    column: null          # set to your timestamp column, e.g. updated_at
  uniqueness:
    key_columns: []       # e.g. [id]
github:
  branch: gh-results
  pages: false
"""


# ------------------------------------------------------------------ demo
def cmd_demo(args: argparse.Namespace) -> int:
    """Generate the demo database and config."""
    db_path, config_path = generate_demo(args.out)
    print(f"demo database : {db_path}")
    print(f"demo config   : {config_path}")
    print("next          : dqfs score --config dqfs-demo.yaml "
          "--dsn sqlite:///demo/quality_demo.db --table customers")
    return 0


# ----------------------------------------------------------------- score
def cmd_score(args: argparse.Namespace) -> int:
    """Load data, run scoring, write artifacts, print the summary."""
    cfg = load_config(args.config)
    if args.target:
        target = args.target
    else:
        target = None
    df, source_label = load_table(
        dsn=args.dsn, table=args.table, query=args.query, csv_path=args.csv
    )
    if args.dataset_name:
        cfg.dataset["name"] = args.dataset_name
    run = run_scoring(df, cfg, source_label, target=target)

    from dqfs.report import write_csv, write_excel, write_html, write_json

    out_dir = Path(args.out)
    artifacts = [
        *write_json(run.result, out_dir),
        write_html(run.result, out_dir),
        write_excel(run.result, out_dir),
        *write_csv(run.result, out_dir),
    ]

    _print_summary(run, artifacts)
    if args.fail_on_gate and run.verdict == "FAIL":
        raise GateFailureError(
            run.verdict, f"quality gates failed (verdict {run.verdict}, DQS {run.dqs:.1f})"
        )
    return 0


def _print_summary(run, artifacts) -> None:
    result = run.result
    print(f"DQFS {__version__} - data quality factor scoring")
    print(f"source        : {result['dataset']['source']}")
    print(f"rows x cols   : {result['dataset']['rows']} x {result['dataset']['columns']}")
    print(f"DQS           : {result['dqs']:.1f} / 100")
    print(f"verdict       : {result['verdict']}")
    print()
    header = f"{'factor':<14}{'score':>8}{'weight':>9}{'ic':>8}{'deep':>8}  status"
    print(header)
    print("-" * len(header))
    for name, info in result["factors"].items():
        score = "-" if info.get("score") is None else f"{info['score']:.3f}"
        weight = "-" if info.get("weight") is None else f"{info['weight']:.3f}"
        ic = "-" if info.get("ic") is None else f"{info['ic']:.2f}"
        deep = "-" if info.get("deep_importance") is None else f"{info['deep_importance']:.2f}"
        print(f"{name:<14}{score:>8}{weight:>9}{ic:>8}{deep:>8}  {info['status']}")
    print()
    print("artifacts:")
    for path in artifacts:
        print(f"  {path}")


# ---------------------------------------------------------------- report
def cmd_report(args: argparse.Namespace) -> int:
    """Re-render artifacts from an existing results/latest.json."""
    from dqfs.report import write_csv, write_excel, write_html

    latest = Path(args.results) / "latest.json"
    if not latest.exists():
        raise ReportError(f"results file not found: {latest} (run `dqfs score` first)")
    result = json.loads(latest.read_text(encoding="utf-8"))
    out_dir = Path(args.out) if args.out else latest.parent
    artifacts = [
        write_html(result, out_dir),
        write_excel(result, out_dir),
        *write_csv(result, out_dir),
    ]
    print(f"re-rendered {len(artifacts)} artifacts from {latest}:")
    for path in artifacts:
        print(f"  {path}")
    return 0


# --------------------------------------------------------------- publish
def cmd_publish(args: argparse.Namespace) -> int:
    """Commit the latest result artifacts to a GitHub repository."""
    from dqfs.github.publisher import GitHubPublisher, resolve_token

    # dry-run validates the plan without credentials
    token = resolve_token(args.token, required=not args.dry_run)
    results_dir = Path(args.results)
    verdict = args.verdict
    if args.status and verdict is None:
        latest = results_dir / "latest.json"
        if latest.exists():
            verdict = json.loads(latest.read_text(encoding="utf-8")).get("verdict")
    publisher = GitHubPublisher(token=token, repo=args.repo)
    out = publisher.publish(
        results_dir,
        branch=args.branch,
        pages=args.pages,
        pages_branch=args.pages_branch,
        verdict=verdict if args.status else None,
        dry_run=args.dry_run,
    )
    if out.dry_run:
        print(f"dry run - would commit {len(out.files)} files to "
              f"{out.repo}@{out.branch}:")
    else:
        print(f"published {len(out.files)} files to {out.repo}@{out.branch} "
              f"(commit {out.commit_sha[:12]})")
    for path in out.files:
        print(f"  {path}")
    if out.pages_updated:
        print(f"pages updated: docs/index.html on {args.pages_branch}")
    if out.status_created:
        print("commit status posted: dqfs/quality-gate")
    return 0


# ---------------------------------------------------------------- doctor
def cmd_doctor(args: argparse.Namespace) -> int:
    """Environment/config/data-source self-check.

    The exit code reflects only critical checks (python, dependencies,
    config, data source). Informational rows such as GITHUB_TOKEN - needed
    solely for ``dqfs publish`` - never fail the doctor.
    """
    checks: list[tuple[str, bool, str, bool]] = []  # (name, ok, detail, critical)

    py_ok = sys.version_info >= (3, 10)
    checks.append((
        "python >= 3.10", py_ok,
        f"{sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro}",
        True,
    ))
    for module in ("numpy", "pandas", "sqlalchemy", "openpyxl", "yaml", "requests"):
        try:
            mod = __import__(module)
            checks.append((f"dependency {module}", True,
                           getattr(mod, "__version__", "?"), True))
        except ImportError as exc:  # pragma: no cover - packaging failure mode
            checks.append((f"dependency {module}", False, str(exc), True))

    if args.config:
        try:
            load_config(args.config)
            checks.append(("config loads", True, str(args.config), True))
        except (DqfsError, ValueError) as exc:
            checks.append(("config loads", False, str(exc), True))

    try:
        df, label = load_table(
            dsn=args.dsn, table=args.table, query=args.query, csv_path=args.csv
        )
        checks.append(("data source reachable", True,
                       f"{label} ({len(df)} rows)", True))
    except DqfsError as exc:
        if args.dsn or args.table or args.query or args.csv:
            checks.append(("data source reachable", False, str(exc), True))
        else:
            checks.append(("data source reachable", True,
                           "not probed (no --dsn/--table/--query/--csv)", False))

    checks.append(("git available", bool(shutil.which("git")),
                   "for push-ready workflows", True))
    import os as _os

    checks.append((
        "GITHUB_TOKEN set", bool(_os.environ.get("GITHUB_TOKEN")),
        "needed only for `dqfs publish`", False,
    ))

    critical = [(n, ok, d) for n, ok, d, c in checks if c]
    info = [(n, ok, d) for n, ok, d, c in checks if not c]
    print(f"DQFS doctor - {sum(1 for _, ok, _ in critical if ok)}/{len(critical)} "
          "critical checks passed")
    for name, ok, detail in critical:
        print(f"  [{'PASS' if ok else 'FAIL'}] {name}: {detail}")
    for name, ok, detail in info:
        print(f"  [{'SET' if ok else 'unset'}] {name}: {detail}")
    return 0 if all(ok for _, ok, _ in critical) else 1


# ------------------------------------------------------------------ init
def cmd_init(args: argparse.Namespace) -> int:
    """Write a starter dqfs.yaml."""
    path = Path(args.path)
    if path.exists() and not args.force:
        print(f"{path} already exists (use --force to overwrite)")
        return 1
    path.write_text(_STARTER_CONFIG, encoding="utf-8")
    print(f"starter config written: {path}")
    return 0


# ---------------------------------------------------------------- parser
def build_parser() -> argparse.ArgumentParser:
    """Build the argument parser (exposed for tests)."""
    parser = argparse.ArgumentParser(
        prog="dqfs",
        description="Data Quality Factor Scoring - deep-ML quality gates "
        "with GitHub-native reporting.",
    )
    parser.add_argument("--version", action="version", version=f"dqfs {__version__}")
    parser.add_argument("-v", "--verbose", action="count", default=0,
                        help="increase log verbosity (-v info, -vv debug)")
    parser.add_argument("--log-json", action="store_true",
                        help="emit one JSON object per log record")
    sub = parser.add_subparsers(dest="command", required=True)

    p_demo = sub.add_parser("demo", help="generate a demo SQLite database")
    p_demo.add_argument("--out", default="demo", help="output directory")
    p_demo.set_defaults(func=cmd_demo)

    p_score = sub.add_parser("score", help="run the scoring pipeline")
    src = p_score.add_argument_group("data source (database or CSV)")
    src.add_argument("--dsn", help="SQLAlchemy DSN, e.g. sqlite:///demo/quality_demo.db")
    src.add_argument("--table", help="table name to score")
    src.add_argument("--query", help="SQL SELECT query to score")
    src.add_argument("--csv", help="path to a CSV file (alternative source)")
    p_score.add_argument("--config", help="dqfs.yaml config path")
    p_score.add_argument("--target", help="supervised target column for the ensemble")
    p_score.add_argument("--out", default="results", help="artifact output directory")
    p_score.add_argument("--dataset-name", help="override the dataset label in reports")
    p_score.add_argument("--fail-on-gate", action="store_true",
                         help="exit 7 when the verdict is FAIL (CI quality gate)")
    p_score.set_defaults(func=cmd_score)

    p_report = sub.add_parser("report", help="re-render reports from results/latest.json")
    p_report.add_argument("--results", default="results", help="results directory")
    p_report.add_argument("--out", help="output directory (default: results dir)")
    p_report.set_defaults(func=cmd_report)

    p_pub = sub.add_parser("publish", help="publish result artifacts to GitHub")
    p_pub.add_argument("--repo", required=True, help="owner/name of the repository")
    p_pub.add_argument("--branch", default="gh-results", help="target branch")
    p_pub.add_argument("--results", default="results", help="results directory")
    p_pub.add_argument("--token", help="GitHub token (default: GITHUB_TOKEN env)")
    p_pub.add_argument("--pages", action="store_true",
                       help="also push the HTML dashboard to docs/ for GitHub Pages")
    p_pub.add_argument("--pages-branch", default=None,
                       help="branch Pages serves from (default: repo default)")
    p_pub.add_argument("--status", action="store_true",
                       help="post a dqfs/quality-gate commit status")
    p_pub.add_argument("--verdict", choices=["PASS", "WARN", "FAIL"],
                       help="override the verdict used for the status")
    p_pub.add_argument("--dry-run", action="store_true",
                       help="print the plan without any API calls")
    p_pub.set_defaults(func=cmd_publish)

    p_doc = sub.add_parser("doctor", help="self-check environment, config and data source")
    p_doc.add_argument("--config", help="config file to validate")
    p_doc.add_argument("--dsn", help="DSN to test")
    p_doc.add_argument("--table", help="table to probe")
    p_doc.add_argument("--query", help="query to probe")
    p_doc.add_argument("--csv", help="CSV path to probe")
    p_doc.set_defaults(func=cmd_doctor)

    p_init = sub.add_parser("init", help="write a starter dqfs.yaml")
    p_init.add_argument("--path", default="dqfs.yaml")
    p_init.add_argument("--force", action="store_true")
    p_init.set_defaults(func=cmd_init)

    return parser


def main(argv: list[str] | None = None) -> int:
    """CLI entry point; returns the process exit code."""
    parser = build_parser()
    args = parser.parse_args(argv)
    setup_logging(args.verbose, args.log_json)
    func: Callable[[argparse.Namespace], int] = args.func
    try:
        return func(args)
    except DqfsError as exc:
        for exc_type, code in _EXIT_CODES:
            if isinstance(exc, exc_type):
                logger.error("%s", exc)
                return code
        logger.error("%s", exc)
        return 1
    except KeyboardInterrupt:  # pragma: no cover
        print("interrupted", file=sys.stderr)
        return 130
    except Exception as exc:  # noqa: BLE001 - final backstop with traceback
        logger.exception("unexpected error: %s", exc)
        return 1


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
